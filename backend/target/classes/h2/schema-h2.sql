-- ============================================================
-- HoneyBee Trace - H2 schema for quick demo
-- ============================================================
-- Mục tiêu DBMS thể hiện trong file này:
-- 1) Tổ chức dữ liệu chuỗi cung ứng: farm -> batch/product -> transport -> store -> customer scan.
-- 2) Ràng buộc toàn vẹn: PK, FK, UNIQUE, CHECK, NOT NULL.
-- 3) Tính minh bạch: audit log, status history, scan log, security alert.
-- 4) An toàn QR: token khó đoán, chữ ký QR, trạng thái QR, cảnh báo clone/copy.
-- 5) Chống Lost Update: VERSION_NO dùng cho optimistic locking.
-- 6) Tối ưu truy xuất QR: index theo token, batch/time, audit/time.
-- ============================================================

DROP VIEW IF EXISTS VW_PUBLIC_TRACE;
DROP TABLE IF EXISTS QR_SECURITY_ALERTS;
DROP TABLE IF EXISTS AUDIT_LOGS;
DROP TABLE IF EXISTS QR_SCAN_LOGS;
DROP TABLE IF EXISTS QR_CODES;
DROP TABLE IF EXISTS PRODUCT_UPDATES;
DROP TABLE IF EXISTS BATCH_STATUS_HISTORY;
DROP TABLE IF EXISTS DISTRIBUTION_HISTORY;
DROP TABLE IF EXISTS CERTIFICATES;
DROP TABLE IF EXISTS TRANSPORT_HISTORY;
DROP TABLE IF EXISTS PRODUCT_ORIGIN;
DROP TABLE IF EXISTS STATUS_TRANSITIONS;
DROP TABLE IF EXISTS PRODUCTS;
DROP TABLE IF EXISTS USERS;
DROP TABLE IF EXISTS TRANSPORTERS;
DROP TABLE IF EXISTS STORES;
DROP TABLE IF EXISTS FARMS;

-- Nông trại/nhà cung cấp: nguồn gốc đầu tiên trong chuỗi cung ứng.
CREATE TABLE FARMS (
    FARM_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FARM_NAME VARCHAR(150) NOT NULL,
    ADDRESS VARCHAR(255) NOT NULL,
    OWNER_NAME VARCHAR(100),
    CERTIFICATION VARCHAR(100),
    CONTACT_PHONE VARCHAR(20),
    CONTACT_EMAIL VARCHAR(100),
    STATUS VARCHAR(20) DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE','INACTIVE')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Đơn vị vận chuyển: tách riêng để phân quyền và tránh nhập text lặp lại.
CREATE TABLE TRANSPORTERS (
    TRANSPORTER_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRANSPORTER_NAME VARCHAR(150) NOT NULL,
    PHONE VARCHAR(30),
    ADDRESS VARCHAR(255),
    CONTACT_PERSON VARCHAR(100),
    STATUS VARCHAR(20) DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE','INACTIVE')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Cửa hàng/nhà hàng/siêu thị nhận lô hàng.
CREATE TABLE STORES (
    STORE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STORE_NAME VARCHAR(150) NOT NULL,
    STORE_TYPE VARCHAR(50) CHECK (STORE_TYPE IN ('SUPERMARKET','CLEAN_FOOD_STORE','RESTAURANT','OTHER')),
    ADDRESS VARCHAR(255),
    CITY VARCHAR(80),
    PHONE VARCHAR(30),
    CONTACT_PERSON VARCHAR(100),
    STATUS VARCHAR(20) DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE','INACTIVE')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tài khoản vận hành. Customer quét QR là public user, không bắt buộc đăng nhập.
CREATE TABLE USERS (
    USER_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    FULL_NAME VARCHAR(100),
    EMAIL VARCHAR(100),
    PHONE VARCHAR(30),
    ROLE VARCHAR(20) NOT NULL CHECK (ROLE IN ('ADMIN','FARMER','TRANSPORTER','STORE')),
    FARM_ID BIGINT,
    TRANSPORTER_ID BIGINT,
    STORE_ID BIGINT,
    STATUS VARCHAR(20) DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE','LOCKED')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_USERS_FARM FOREIGN KEY (FARM_ID) REFERENCES FARMS(FARM_ID),
    CONSTRAINT FK_USERS_TRANSPORTER FOREIGN KEY (TRANSPORTER_ID) REFERENCES TRANSPORTERS(TRANSPORTER_ID),
    CONSTRAINT FK_USERS_STORE FOREIGN KEY (STORE_ID) REFERENCES STORES(STORE_ID)
);

-- STATUS_TRANSITIONS biến luồng trạng thái thành dữ liệu DB.
-- Ưu điểm: có thể kiểm tra trạng thái hợp lệ bằng procedure, không hard-code toàn bộ ở UI.
CREATE TABLE STATUS_TRANSITIONS (
    FROM_STATUS VARCHAR(30),
    TO_STATUS VARCHAR(30) NOT NULL,
    ALLOWED_ROLE VARCHAR(20) NOT NULL,
    DESCRIPTION VARCHAR(255),
    PRIMARY KEY (FROM_STATUS, TO_STATUS, ALLOWED_ROLE)
);

-- PRODUCTS ở bản demo này được hiểu là từng lô sản phẩm/batch cụ thể.
-- VERSION_NO dùng để chống Lost Update khi nhiều người cập nhật cùng một lô.
CREATE TABLE PRODUCTS (
    PRODUCT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FARM_ID BIGINT NOT NULL,
    BATCH_CODE VARCHAR(40) UNIQUE,
    PRODUCT_NAME VARCHAR(150) NOT NULL,
    CATEGORY VARCHAR(80) NOT NULL,
    DESCRIPTION CLOB,
    QUALITY_SUMMARY VARCHAR(500),
    PRICE DECIMAL(12,2) CHECK (PRICE >= 0),
    QUANTITY DECIMAL(12,2) DEFAULT 0 CHECK (QUANTITY >= 0),
    UNIT VARCHAR(20) DEFAULT 'kg',
    STATUS VARCHAR(30) DEFAULT 'CREATED' CHECK (STATUS IN (
        'CREATED','FARM_CONFIRMED','CERTIFIED','READY_FOR_TRANSPORT','IN_TRANSIT','DELIVERED','DELIVERED_TO_STORE',
        'STORE_RECEIVED','AVAILABLE_FOR_SALE','SOLD_OUT','EXPIRED','REVOKED','REJECTED','CANCELLED'
    )),
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    IMAGE_URL VARCHAR(500),
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PRODUCTS_FARMS FOREIGN KEY (FARM_ID) REFERENCES FARMS(FARM_ID)
);

-- Thông tin nguồn gốc/nuôi trồng của từng lô.
CREATE TABLE PRODUCT_ORIGIN (
    ORIGIN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID BIGINT NOT NULL UNIQUE,
    CULTIVATION_PLACE VARCHAR(255),
    SOWING_DATE DATE,
    HARVEST_DATE DATE,
    EXPIRED_DATE DATE,
    PRODUCTION_PROCESS CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ORIGIN_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_ORIGIN_DATES CHECK (EXPIRED_DATE IS NULL OR HARVEST_DATE IS NULL OR EXPIRED_DATE >= HARVEST_DATE)
);

-- Lịch sử vận chuyển là append-log nghiệp vụ: nên thêm dòng mới thay vì sửa lịch sử cũ.
CREATE TABLE TRANSPORT_HISTORY (
    TRANSPORT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID BIGINT NOT NULL,
    TRANSPORTER_ID BIGINT,
    TRANSPORT_COMPANY VARCHAR(150),
    FROM_LOCATION VARCHAR(255),
    TO_LOCATION VARCHAR(255),
    TRANSPORT_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STORAGE_TEMPERATURE DECIMAL(5,2),
    STATUS VARCHAR(30) DEFAULT 'IN_TRANSIT' CHECK (STATUS IN ('PENDING','IN_TRANSIT','DELIVERED','DELIVERED_TO_STORE','REJECTED')),
    NOTE VARCHAR(500),
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TRANSPORT_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_TRANSPORT_TRANSPORTER FOREIGN KEY (TRANSPORTER_ID) REFERENCES TRANSPORTERS(TRANSPORTER_ID)
);

-- Chứng chỉ tách riêng để quản lý hết hạn/thu hồi/chưa duyệt rõ ràng.
CREATE TABLE CERTIFICATES (
    CERTIFICATE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FARM_ID BIGINT,
    PRODUCT_ID BIGINT,
    CERTIFICATE_NAME VARCHAR(150) NOT NULL,
    ISSUED_BY VARCHAR(150),
    ISSUE_DATE DATE,
    EXPIRED_DATE DATE,
    FILE_URL VARCHAR(500),
    STATUS VARCHAR(20) DEFAULT 'VALID' CHECK (STATUS IN ('VALID','EXPIRING_SOON','EXPIRED','REVOKED','PENDING')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CERT_FARM FOREIGN KEY (FARM_ID) REFERENCES FARMS(FARM_ID),
    CONSTRAINT FK_CERT_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_CERT_DATES CHECK (EXPIRED_DATE IS NULL OR ISSUE_DATE IS NULL OR EXPIRED_DATE >= ISSUE_DATE)
);

-- Cửa hàng xác nhận nhận hàng và cập nhật bán hết.
CREATE TABLE DISTRIBUTION_HISTORY (
    DISTRIBUTION_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID BIGINT NOT NULL,
    STORE_ID BIGINT NOT NULL,
    RECEIVED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    RECEIVED_BY BIGINT,
    QUANTITY_RECEIVED DECIMAL(12,2) CHECK (QUANTITY_RECEIVED IS NULL OR QUANTITY_RECEIVED >= 0),
    STATUS VARCHAR(30) DEFAULT 'RECEIVED' CHECK (STATUS IN ('PENDING_RECEIVE','RECEIVED','REJECTED','AVAILABLE_FOR_SALE','SOLD_OUT')),
    NOTE VARCHAR(500),
    CONSTRAINT FK_DIST_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_DIST_STORE FOREIGN KEY (STORE_ID) REFERENCES STORES(STORE_ID)
);

-- Lịch sử trạng thái của lô hàng: phục vụ audit nghiệp vụ và truy xuất timeline.
CREATE TABLE BATCH_STATUS_HISTORY (
    STATUS_HISTORY_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID BIGINT NOT NULL,
    OLD_STATUS VARCHAR(30),
    NEW_STATUS VARCHAR(30) NOT NULL,
    CHANGED_BY BIGINT,
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    NOTE VARCHAR(500),
    CONSTRAINT FK_STATUS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);

-- Nhật ký cập nhật mô tả; dùng cho timeline người dùng cuối.
CREATE TABLE PRODUCT_UPDATES (
    UPDATE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID BIGINT NOT NULL,
    UPDATE_TITLE VARCHAR(150) NOT NULL,
    UPDATE_CONTENT CLOB,
    UPDATED_BY VARCHAR(100),
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_UPDATES_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);

-- QR_CODES: token khó đoán + signature để ngăn tự tạo QR giả.
-- Lưu ý: chữ ký không chống copy QR thật, nên cần thêm scan log + alert để phát hiện clone.
CREATE TABLE QR_CODES (
    QR_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID BIGINT NOT NULL,
    QR_TOKEN VARCHAR(100) NOT NULL UNIQUE,
    QR_SIGNATURE VARCHAR(256) NOT NULL,
    QR_URL VARCHAR(600) NOT NULL,
    QR_IMAGE_URL VARCHAR(500),
    STATUS VARCHAR(20) DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE','EXPIRED','REVOKED','SUSPICIOUS')),
    -- SALE_STATUS giúp cửa hàng/POS đánh dấu QR/lô đã bán.
    -- Khi khách quét lại QR đã SOLD, hệ thống cảnh báo để hạn chế QR bị copy dán lên hàng khác.
    SALE_STATUS VARCHAR(20) DEFAULT 'NOT_SOLD' CHECK (SALE_STATUS IN ('NOT_SOLD','SOLD','RETURNED')),
    SOLD_AT TIMESTAMP,
    SOLD_BY_STORE_ID BIGINT,
    SOLD_NOTE VARCHAR(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    EXPIRED_AT TIMESTAMP,
    REVOKED_AT TIMESTAMP,
    REVOKED_REASON VARCHAR(500),
    CONSTRAINT FK_QR_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_QR_SOLD_STORE FOREIGN KEY (SOLD_BY_STORE_ID) REFERENCES STORES(STORE_ID)
);

-- Mọi lần quét QR đều được ghi lại để tính rủi ro và làm bằng chứng minh bạch.
CREATE TABLE QR_SCAN_LOGS (
    SCAN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QR_TOKEN VARCHAR(100),
    PRODUCT_ID BIGINT,
    IP_ADDRESS VARCHAR(50),
    USER_AGENT VARCHAR(500),
    DEVICE_INFO VARCHAR(300),
    LOCATION_TEXT VARCHAR(200),
    RESULT_STATUS VARCHAR(30) DEFAULT 'SUCCESS' CHECK (RESULT_STATUS IN ('SUCCESS','INVALID_TOKEN','INVALID_SIGNATURE','EXPIRED_QR','REVOKED_QR','ERROR')),
    WARNING_LEVEL VARCHAR(20) DEFAULT 'NONE' CHECK (WARNING_LEVEL IN ('NONE','LOW','MEDIUM','HIGH','CRITICAL')),
    WARNING_MESSAGE VARCHAR(1000),
    SCANNED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_SCAN_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE SET NULL
);

-- Bảng cảnh báo an toàn QR: phát hiện clone, scan quá nhiều, scan sau SOLD_OUT/EXPIRED.
CREATE TABLE QR_SECURITY_ALERTS (
    ALERT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QR_TOKEN VARCHAR(100),
    PRODUCT_ID BIGINT,
    ALERT_TYPE VARCHAR(50) NOT NULL,
    ALERT_LEVEL VARCHAR(20) NOT NULL CHECK (ALERT_LEVEL IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    ALERT_MESSAGE VARCHAR(1000) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    RESOLVED_STATUS VARCHAR(20) DEFAULT 'OPEN' CHECK (RESOLVED_STATUS IN ('OPEN','INVESTIGATING','RESOLVED','FALSE_POSITIVE')),
    CONSTRAINT FK_ALERT_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE SET NULL
);

-- AUDIT_LOGS là log kỹ thuật/nghiệp vụ cấp DBMS.
-- Trong Oracle thật có trigger chặn UPDATE/DELETE để đảm bảo append-only.
CREATE TABLE AUDIT_LOGS (
    AUDIT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TABLE_NAME VARCHAR(80) NOT NULL,
    RECORD_ID VARCHAR(80),
    ACTION_TYPE VARCHAR(30) NOT NULL CHECK (ACTION_TYPE IN ('INSERT','UPDATE','DELETE','LOGIN','SCAN','STATUS_CHANGE','QR_ALERT','REVOKE')),
    OLD_DATA CLOB,
    NEW_DATA CLOB,
    PERFORMED_BY VARCHAR(100),
    IP_ADDRESS VARCHAR(50),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Index phục vụ mục tiêu truy xuất QR < 2 giây và demo execution plan.
CREATE INDEX IDX_PRODUCTS_FARM ON PRODUCTS(FARM_ID);
CREATE INDEX IDX_PRODUCTS_STATUS ON PRODUCTS(STATUS);
CREATE INDEX IDX_PRODUCTS_BATCH_CODE ON PRODUCTS(BATCH_CODE);
CREATE UNIQUE INDEX IDX_QR_TOKEN ON QR_CODES(QR_TOKEN);
CREATE INDEX IDX_QR_PRODUCT ON QR_CODES(PRODUCT_ID);
CREATE INDEX IDX_QR_STATUS ON QR_CODES(STATUS);
CREATE INDEX IDX_QR_SALE_STATUS ON QR_CODES(SALE_STATUS, SOLD_AT);
CREATE INDEX IDX_TRANSPORT_PRODUCT_TIME ON TRANSPORT_HISTORY(PRODUCT_ID, TRANSPORT_TIME);
CREATE INDEX IDX_STATUS_PRODUCT_TIME ON BATCH_STATUS_HISTORY(PRODUCT_ID, CHANGED_AT);
CREATE INDEX IDX_CERT_PRODUCT ON CERTIFICATES(PRODUCT_ID);
CREATE INDEX IDX_DIST_PRODUCT ON DISTRIBUTION_HISTORY(PRODUCT_ID);
CREATE INDEX IDX_SCAN_TOKEN_TIME ON QR_SCAN_LOGS(QR_TOKEN, SCANNED_AT);
CREATE INDEX IDX_SCAN_PRODUCT_TIME ON QR_SCAN_LOGS(PRODUCT_ID, SCANNED_AT);
CREATE INDEX IDX_ALERT_PRODUCT_TIME ON QR_SECURITY_ALERTS(PRODUCT_ID, CREATED_AT);
CREATE INDEX IDX_AUDIT_RECORD_TIME ON AUDIT_LOGS(RECORD_ID, CREATED_AT);

-- View gom dữ liệu công khai để API trace lấy nhanh, tránh frontend tự join dữ liệu.
CREATE VIEW VW_PUBLIC_TRACE AS
SELECT
    p.PRODUCT_ID,
    p.BATCH_CODE,
    p.PRODUCT_NAME,
    p.CATEGORY,
    p.DESCRIPTION,
    p.QUALITY_SUMMARY,
    p.PRICE,
    p.QUANTITY,
    p.UNIT,
    p.STATUS AS PRODUCT_STATUS,
    p.VERSION_NO,
    p.IMAGE_URL,
    p.CREATED_AT AS PRODUCT_CREATED_AT,
    p.UPDATED_AT AS PRODUCT_UPDATED_AT,
    f.FARM_ID,
    f.FARM_NAME,
    f.ADDRESS AS FARM_ADDRESS,
    f.OWNER_NAME,
    f.CERTIFICATION,
    f.CONTACT_PHONE,
    f.CONTACT_EMAIL,
    o.CULTIVATION_PLACE,
    o.SOWING_DATE,
    o.HARVEST_DATE,
    o.EXPIRED_DATE,
    o.PRODUCTION_PROCESS,
    CASE WHEN o.HARVEST_DATE IS NULL THEN NULL ELSE DATEDIFF('DAY', o.HARVEST_DATE, CURRENT_DATE) END AS DAYS_AFTER_HARVEST,
    CASE WHEN o.EXPIRED_DATE IS NULL THEN 'UNKNOWN'
         WHEN o.EXPIRED_DATE < CURRENT_DATE THEN 'EXPIRED'
         WHEN DATEDIFF('DAY', CURRENT_DATE, o.EXPIRED_DATE) <= 2 THEN 'NEAR_EXPIRED'
         ELSE 'FRESH' END AS FRESHNESS_STATUS,
    q.QR_TOKEN,
    q.QR_SIGNATURE,
    q.QR_URL,
    q.QR_IMAGE_URL,
    q.STATUS AS QR_STATUS,
    q.SALE_STATUS AS QR_SALE_STATUS,
    q.SOLD_AT,
    q.SOLD_BY_STORE_ID,
    q.SOLD_NOTE
FROM PRODUCTS p
JOIN FARMS f ON p.FARM_ID = f.FARM_ID
LEFT JOIN PRODUCT_ORIGIN o ON p.PRODUCT_ID = o.PRODUCT_ID
LEFT JOIN QR_CODES q ON p.PRODUCT_ID = q.PRODUCT_ID;
