-- ============================================================
-- 02_tables.sql - Detailed normalized schema for DBMS grading
-- ============================================================
-- Điểm cần trình bày trong báo cáo:
-- - PK/FK/CHECK/UNIQUE bảo vệ toàn vẹn dữ liệu.
-- - Lịch sử quan trọng dùng append-only log: AUDIT_LOGS, QR_SCAN_LOGS, STATUS_HISTORY.
-- - VERSION_NO trong PRODUCTS dùng demo Lost Update.
-- - QR_CODES + QR_SCAN_LOGS + QR_SECURITY_ALERTS xử lý rủi ro QR bị copy.
-- ============================================================

CREATE TABLE FARMS (
    FARM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FARM_NAME NVARCHAR2(150) NOT NULL,
    ADDRESS NVARCHAR2(255) NOT NULL,
    OWNER_NAME NVARCHAR2(100),
    CERTIFICATION NVARCHAR2(100),
    CONTACT_PHONE VARCHAR2(20),
    CONTACT_EMAIL VARCHAR2(100),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_FARMS_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE TRANSPORTERS (
    TRANSPORTER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRANSPORTER_NAME NVARCHAR2(150) NOT NULL,
    PHONE VARCHAR2(30),
    ADDRESS NVARCHAR2(255),
    CONTACT_PERSON NVARCHAR2(100),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_TRANSPORTERS_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE STORES (
    STORE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STORE_NAME NVARCHAR2(150) NOT NULL,
    STORE_TYPE VARCHAR2(50),
    ADDRESS NVARCHAR2(255),
    CITY NVARCHAR2(80),
    PHONE VARCHAR2(30),
    CONTACT_PERSON NVARCHAR2(100),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_STORES_TYPE CHECK (STORE_TYPE IN ('SUPERMARKET','CLEAN_FOOD_STORE','RESTAURANT','OTHER')),
    CONSTRAINT CK_STORES_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    FULL_NAME NVARCHAR2(100),
    EMAIL VARCHAR2(100),
    PHONE VARCHAR2(30),
    ROLE VARCHAR2(20) NOT NULL,
    FARM_ID NUMBER,
    TRANSPORTER_ID NUMBER,
    STORE_ID NUMBER,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('ADMIN','FARMER','TRANSPORTER','STORE')),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE','LOCKED')),
    CONSTRAINT FK_USERS_FARM FOREIGN KEY (FARM_ID) REFERENCES FARMS(FARM_ID),
    CONSTRAINT FK_USERS_TRANSPORTER FOREIGN KEY (TRANSPORTER_ID) REFERENCES TRANSPORTERS(TRANSPORTER_ID),
    CONSTRAINT FK_USERS_STORE FOREIGN KEY (STORE_ID) REFERENCES STORES(STORE_ID)
);

CREATE TABLE STATUS_TRANSITIONS (
    FROM_STATUS VARCHAR2(30),
    TO_STATUS VARCHAR2(30) NOT NULL,
    ALLOWED_ROLE VARCHAR2(20) NOT NULL,
    DESCRIPTION NVARCHAR2(255),
    CONSTRAINT PK_STATUS_TRANSITIONS PRIMARY KEY (FROM_STATUS, TO_STATUS, ALLOWED_ROLE)
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FARM_ID NUMBER NOT NULL,
    BATCH_CODE VARCHAR2(40) UNIQUE,
    PRODUCT_NAME NVARCHAR2(150) NOT NULL,
    CATEGORY NVARCHAR2(80) NOT NULL,
    DESCRIPTION NCLOB,
    QUALITY_SUMMARY NVARCHAR2(500),
    PRICE NUMBER(12,2) DEFAULT 0,
    QUANTITY NUMBER(12,2) DEFAULT 0,
    UNIT NVARCHAR2(20) DEFAULT 'kg',
    STATUS VARCHAR2(30) DEFAULT 'CREATED' NOT NULL,
    VERSION_NO NUMBER DEFAULT 0 NOT NULL,
    IMAGE_URL VARCHAR2(500),
    CREATED_BY NUMBER,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PRODUCTS_FARMS FOREIGN KEY (FARM_ID) REFERENCES FARMS(FARM_ID),
    CONSTRAINT CK_PRODUCTS_PRICE CHECK (PRICE >= 0),
    CONSTRAINT CK_PRODUCTS_QUANTITY CHECK (QUANTITY >= 0),
    CONSTRAINT CK_PRODUCTS_STATUS CHECK (STATUS IN ('CREATED','FARM_CONFIRMED','CERTIFIED','READY_FOR_TRANSPORT','IN_TRANSIT','DELIVERED','STORE_RECEIVED','AVAILABLE_FOR_SALE','SOLD_OUT','EXPIRED','REVOKED','REJECTED','CANCELLED'))
);

CREATE TABLE PRODUCT_ORIGIN (
    ORIGIN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER NOT NULL UNIQUE,
    CULTIVATION_PLACE NVARCHAR2(255),
    SOWING_DATE DATE,
    HARVEST_DATE DATE,
    EXPIRED_DATE DATE,
    PRODUCTION_PROCESS NCLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ORIGIN_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_ORIGIN_DATES CHECK (EXPIRED_DATE IS NULL OR HARVEST_DATE IS NULL OR EXPIRED_DATE >= HARVEST_DATE)
);

CREATE TABLE TRANSPORT_HISTORY (
    TRANSPORT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER NOT NULL,
    TRANSPORTER_ID NUMBER,
    TRANSPORT_COMPANY NVARCHAR2(150),
    FROM_LOCATION NVARCHAR2(255),
    TO_LOCATION NVARCHAR2(255),
    TRANSPORT_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STORAGE_TEMPERATURE NUMBER(5,2),
    STATUS VARCHAR2(30) DEFAULT 'IN_TRANSIT' NOT NULL,
    NOTE NVARCHAR2(500),
    CREATED_BY NUMBER,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TRANSPORT_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_TRANSPORT_TRANSPORTER FOREIGN KEY (TRANSPORTER_ID) REFERENCES TRANSPORTERS(TRANSPORTER_ID),
    CONSTRAINT CK_TRANSPORT_STATUS CHECK (STATUS IN ('PENDING','IN_TRANSIT','DELIVERED','REJECTED'))
);

CREATE TABLE CERTIFICATES (
    CERTIFICATE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FARM_ID NUMBER,
    PRODUCT_ID NUMBER,
    CERTIFICATE_NAME NVARCHAR2(150) NOT NULL,
    ISSUED_BY NVARCHAR2(150),
    ISSUE_DATE DATE,
    EXPIRED_DATE DATE,
    FILE_URL VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'VALID' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CERT_FARM FOREIGN KEY (FARM_ID) REFERENCES FARMS(FARM_ID),
    CONSTRAINT FK_CERT_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_CERT_STATUS CHECK (STATUS IN ('VALID','EXPIRING_SOON','EXPIRED','REVOKED','PENDING')),
    CONSTRAINT CK_CERT_DATES CHECK (EXPIRED_DATE IS NULL OR ISSUE_DATE IS NULL OR EXPIRED_DATE >= ISSUE_DATE)
);

CREATE TABLE DISTRIBUTION_HISTORY (
    DISTRIBUTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER NOT NULL,
    STORE_ID NUMBER NOT NULL,
    RECEIVED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    RECEIVED_BY NUMBER,
    QUANTITY_RECEIVED NUMBER(12,2),
    STATUS VARCHAR2(30) DEFAULT 'RECEIVED' NOT NULL,
    NOTE NVARCHAR2(500),
    CONSTRAINT FK_DIST_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_DIST_STORE FOREIGN KEY (STORE_ID) REFERENCES STORES(STORE_ID),
    CONSTRAINT CK_DIST_QTY CHECK (QUANTITY_RECEIVED IS NULL OR QUANTITY_RECEIVED >= 0),
    CONSTRAINT CK_DIST_STATUS CHECK (STATUS IN ('PENDING_RECEIVE','RECEIVED','REJECTED','AVAILABLE_FOR_SALE','SOLD_OUT'))
);

CREATE TABLE BATCH_STATUS_HISTORY (
    STATUS_HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER NOT NULL,
    OLD_STATUS VARCHAR2(30),
    NEW_STATUS VARCHAR2(30) NOT NULL,
    CHANGED_BY NUMBER,
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    NOTE NVARCHAR2(500),
    CONSTRAINT FK_STATUS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);

CREATE TABLE PRODUCT_UPDATES (
    UPDATE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER NOT NULL,
    UPDATE_TITLE NVARCHAR2(150) NOT NULL,
    UPDATE_CONTENT NCLOB,
    UPDATED_BY NVARCHAR2(100),
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_UPDATES_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);

CREATE TABLE QR_CODES (
    QR_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER NOT NULL,
    QR_TOKEN VARCHAR2(100) NOT NULL UNIQUE,
    QR_SIGNATURE VARCHAR2(256) NOT NULL,
    QR_URL VARCHAR2(600) NOT NULL,
    QR_IMAGE_URL VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    -- SALE_STATUS ghi nhận QR/lô đã bán hay chưa. Đây là lớp chống copy QR thực tế hơn scan-count.
    SALE_STATUS VARCHAR2(20) DEFAULT 'NOT_SOLD' NOT NULL,
    SOLD_AT TIMESTAMP,
    SOLD_BY_STORE_ID NUMBER,
    SOLD_NOTE NVARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    EXPIRED_AT TIMESTAMP,
    REVOKED_AT TIMESTAMP,
    REVOKED_REASON NVARCHAR2(500),
    CONSTRAINT FK_QR_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_QR_SOLD_STORE FOREIGN KEY (SOLD_BY_STORE_ID) REFERENCES STORES(STORE_ID),
    CONSTRAINT CK_QR_STATUS CHECK (STATUS IN ('ACTIVE','EXPIRED','REVOKED','SUSPICIOUS')),
    CONSTRAINT CK_QR_SALE_STATUS CHECK (SALE_STATUS IN ('NOT_SOLD','SOLD','RETURNED'))
);

CREATE TABLE QR_SCAN_LOGS (
    SCAN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QR_TOKEN VARCHAR2(100),
    PRODUCT_ID NUMBER,
    IP_ADDRESS VARCHAR2(50),
    USER_AGENT VARCHAR2(500),
    DEVICE_INFO VARCHAR2(300),
    LOCATION_TEXT NVARCHAR2(200),
    RESULT_STATUS VARCHAR2(30) DEFAULT 'SUCCESS' NOT NULL,
    WARNING_LEVEL VARCHAR2(20) DEFAULT 'NONE' NOT NULL,
    WARNING_MESSAGE NVARCHAR2(1000),
    SCANNED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_SCAN_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE SET NULL,
    CONSTRAINT CK_SCAN_RESULT CHECK (RESULT_STATUS IN ('SUCCESS','INVALID_TOKEN','INVALID_SIGNATURE','EXPIRED_QR','REVOKED_QR','ERROR')),
    CONSTRAINT CK_SCAN_WARNING CHECK (WARNING_LEVEL IN ('NONE','LOW','MEDIUM','HIGH','CRITICAL'))
);

CREATE TABLE QR_SECURITY_ALERTS (
    ALERT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QR_TOKEN VARCHAR2(100),
    PRODUCT_ID NUMBER,
    ALERT_TYPE VARCHAR2(50) NOT NULL,
    ALERT_LEVEL VARCHAR2(20) NOT NULL,
    ALERT_MESSAGE NVARCHAR2(1000) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    RESOLVED_STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    CONSTRAINT FK_ALERT_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE SET NULL,
    CONSTRAINT CK_ALERT_LEVEL CHECK (ALERT_LEVEL IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    CONSTRAINT CK_ALERT_STATUS CHECK (RESOLVED_STATUS IN ('OPEN','INVESTIGATING','RESOLVED','FALSE_POSITIVE'))
);

CREATE TABLE AUDIT_LOGS (
    AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TABLE_NAME VARCHAR2(80) NOT NULL,
    RECORD_ID VARCHAR2(80),
    ACTION_TYPE VARCHAR2(30) NOT NULL,
    OLD_DATA NCLOB,
    NEW_DATA NCLOB,
    PERFORMED_BY VARCHAR2(100),
    IP_ADDRESS VARCHAR2(50),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_AUDIT_ACTION CHECK (ACTION_TYPE IN ('INSERT','UPDATE','DELETE','LOGIN','SCAN','STATUS_CHANGE','QR_ALERT','REVOKE'))
);

